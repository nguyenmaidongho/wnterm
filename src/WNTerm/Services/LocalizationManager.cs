        bool isVi = string.Equals(language, "vi", StringComparison.OrdinalIgnoreCase);
        CurrentLanguage = isVi ? "vi" : "en";
        var dict = isVi ? Vietnamese : English;

        var resources = Application.Current?.Resources;
        if (resources == null) return;

        foreach (var kv in dict)
        {
            resources[kv.Key] = kv.Value;
        }
    }

    public static string Get(string key, params object[] args)
    {
        var dict = string.Equals(CurrentLanguage, "vi", StringComparison.OrdinalIgnoreCase) ? Vietnamese : English;
        if (!dict.TryGetValue(key, out var val))
        {
            if (Application.Current?.Resources.Contains(key) == true)
            {
                val = Application.Current.Resources[key]?.ToString() ?? key;
            }
            else
            {
                val = key;
            }
        }
        return args.Length > 0 ? string.Format(val, args) : val;
    }
